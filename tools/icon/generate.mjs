// Development-time tool: turns the app icon artwork (artwork/icon.svg) into every icon file the app and
// F-Droid need. Not part of the app. Run: cd tools/icon && npm install && npm run generate
//
// What it writes (all overwritten each run, so never edit them by hand):
//   app/src/main/res/values/ic_launcher_background.xml   adaptive icon background colour (Android 8+)
//   app/src/main/res/drawable/ic_launcher_foreground.xml  adaptive icon foreground, a vector drawable (Android 8+)
//   app/src/main/res/drawable/ic_launcher_monochrome.xml  one-colour layer for "Themed icons" (Android 13+)
//   app/src/main/res/mipmap-*/ic_launcher.png             ready-made pictures for Android 7 (48 to 192 px)
//   fastlane/metadata/android/en-US/images/icon.png      512 px store icon for F-Droid
//
// How the artwork maps onto an adaptive icon
// (https://developer.android.com/develop/ui/views/launch/icon_design_adaptive):
//   - each layer is 108 x 108 dp; launchers show the middle 72 x 72 dp, cut to their own shape;
//   - the artwork's square canvas (445 units) = that visible 72 dp, so 1 unit = 72/445 dp, offset 18 dp;
//   - the first shape covering the whole canvas is the background (its colour becomes the background layer;
//     its rounded corners are only for the PNGs, because on Android 8+ the launcher cuts the shape itself);
//   - everything after it is the foreground. Nothing may be cut off by the roundest launcher shape, a circle of
//     72 dp (radius 36 dp): if the foreground reaches further, it is scaled down around the centre just enough
//     (the factor is printed). Key content belongs inside the 66 dp "safe zone" circle (radius 33 dp); a part
//     between 33 and 36 dp (e.g. the tip of a speech-bubble tail) is reported, not refused.
//
// The SVG reader is deliberately small: it understands what SVGMaker writes for this artwork (rect with
// rounded corners, circle, path with M/L/H/V/Z, group transforms that scale evenly and move) and stops with a
// clear message on anything else, instead of guessing.
//
// The rendering (SVG reading, PNG pictures) uses Chromium through Playwright, the same engine as a browser.

import { chromium } from 'playwright';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SOURCE = join(ROOT, 'artwork', 'icon.svg');
const RES = join(ROOT, 'app', 'src', 'main', 'res');
const STORE_ICON = join(ROOT, 'fastlane', 'metadata', 'android', 'en-US', 'images', 'icon.png');
// Legacy launcher icon = 48 dp; one PNG per screen density (mdpi = 1x … xxxhdpi = 4x).
const LEGACY = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
const STORE_PX = 512;

const LAYER_DP = 108, VISIBLE_DP = 72, SAFE_RADIUS_DP = 33, VISIBLE_RADIUS_DP = 36;
// Points of the same path closer than this (in artwork units) are treated as the same line. SVGMaker leaves
// gaps/overlaps of up to ~0.001 between pixel rows; snapping them makes neighbouring rows meet exactly.
const SNAP = 0.01;

const HEADER = '<!-- Generated by tools/icon/generate.mjs from artwork/icon.svg. Do not edit by hand:\n'
    + '     change the artwork and run the generator again (see RELEASE.md section 2). -->\n';

// ---------- 1. read the artwork with Chromium (it resolves styles and transforms for us) ----------

async function readArtwork(page, svgText) {
    await page.setContent(`<!doctype html><body style="margin:0">${svgText}</body>`);
    return page.evaluate(() => {
        const svg = document.querySelector('svg');
        const vb = svg.viewBox.baseVal;
        const shapes = [];
        // things this reader does not understand: report them instead of drawing something wrong
        const unsupported = [...svg.querySelectorAll('clipPath, mask, pattern, linearGradient, radialGradient, filter, use, image, text, symbol, marker, foreignObject')]
            .map(el => el.tagName);
        for (const el of svg.querySelectorAll('*')) {
            const tag = el.tagName.toLowerCase();
            if (!['rect', 'path', 'circle', 'ellipse', 'line', 'polygon', 'polyline', 'text', 'image', 'use'].includes(tag)) continue;
            const cs = getComputedStyle(el);
            if (cs.visibility === 'hidden' || cs.display === 'none' || el.closest('defs')) continue;
            const m = el.getCTM();
            shapes.push({
                tag,
                ctm: [m.a, m.b, m.c, m.d, m.e, m.f],
                attr: Object.fromEntries([...el.attributes].map(a => [a.name, a.value])),
                fill: cs.fill, fillRule: cs.fillRule, stroke: cs.stroke, strokeWidth: parseFloat(cs.strokeWidth),
                lineJoin: cs.strokeLinejoin, opacity: [cs.opacity, cs.fillOpacity, cs.strokeOpacity].map(Number),
            });
        }
        return { viewBox: [vb.x, vb.y, vb.width, vb.height], shapes, unsupported };
    });
}

// ---------- 2. geometry in artwork units ----------

function fail(msg) { throw new Error(msg + '\n(artwork/icon.svg uses something tools/icon/generate.mjs does not support)'); }
/** Stops for a problem with the drawing itself (e.g. too big), not with the SVG features it uses. */
function stop(msg) { throw new Error(msg); }

function transformOf(s) {
    const [a, b, c, d, e, f] = s.ctm;
    if (Math.abs(b) > 1e-9 || Math.abs(c) > 1e-9 || Math.abs(a - d) > 1e-9 || a <= 0) {
        fail(`<${s.tag}> has a rotation, skew, flip or uneven scale (matrix ${s.ctm.join(' ')})`);
    }
    return { k: a, tx: e, ty: f, map: (x, y) => [a * x + e, d * y + f] };
}

function colourOf(css, what) {
    if (css === 'none') return null;
    const m = /^rgb\((\d+), (\d+), (\d+)\)$/.exec(css);
    if (!m) fail(`${what} colour "${css}" is not a plain opaque colour`);
    return '#' + m.slice(1).map(n => Number(n).toString(16).padStart(2, '0').toUpperCase()).join('');
}

/** Absolute M/L/H/V/Z path data (and relative forms) → list of closed polygons [[x, y], …]. */
function parsePolygons(d) {
    const tokens = d.match(/[a-zA-Z]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?/g) || [];
    const polys = [];
    let cmd = null, cur = null, x = 0, y = 0, i = 0;
    const num = () => { const v = Number(tokens[i++]); if (!Number.isFinite(v)) fail(`bad number in path "${d.slice(0, 40)}…"`); return v; };
    while (i < tokens.length) {
        if (/[a-zA-Z]/.test(tokens[i])) cmd = tokens[i++];
        switch (cmd) {
            case 'M': case 'm': {
                const nx = num(), ny = num();
                [x, y] = cmd === 'm' && cur ? [x + nx, y + ny] : [nx, ny];
                cur = [[x, y]]; polys.push(cur);
                cmd = cmd === 'm' ? 'l' : 'L';          // more pairs after M are line-tos
                break;
            }
            case 'L': case 'l': { const nx = num(), ny = num(); [x, y] = cmd === 'l' ? [x + nx, y + ny] : [nx, ny]; cur.push([x, y]); break; }
            case 'H': case 'h': { const v = num(); x = cmd === 'h' ? x + v : v; cur.push([x, y]); break; }
            case 'V': case 'v': { const v = num(); y = cmd === 'v' ? y + v : v; cur.push([x, y]); break; }
            case 'Z': case 'z': [x, y] = cur[0]; cur = null; break;
            default: fail(`path command "${cmd}" (only M, L, H, V and Z are supported)`);
        }
    }
    return polys.map(p => {                         // drop a repeated closing point
        const [a, b] = [p[0], p[p.length - 1]];
        return p.length > 1 && a[0] === b[0] && a[1] === b[1] ? p.slice(0, -1) : p;
    });
}

/** Moves values that are within SNAP of each other onto one value (their average), separately for x and y. */
function snap(polys) {
    for (const axis of [0, 1]) {
        const values = [...new Set(polys.flat().map(p => p[axis]))].sort((a, b) => a - b);
        const to = new Map();
        for (let i = 0; i < values.length;) {
            let j = i;
            while (j + 1 < values.length && values[j + 1] - values[i] < SNAP) j++;
            const group = values.slice(i, j + 1), mean = group.reduce((s, v) => s + v, 0) / group.length;
            group.forEach(v => to.set(v, mean));
            i = j + 1;
        }
        polys.forEach(p => p.forEach(pt => { pt[axis] = to.get(pt[axis]); }));
    }
    return polys;
}

/** One visible artwork shape → { kind: 'roundRect' | 'polygons', … } in artwork units, colours as #RRGGBB. */
function toShape(s) {
    if (s.opacity.some(o => o !== 1)) fail(`<${s.tag}> is partly transparent`);
    const t = transformOf(s);
    const fill = colourOf(s.fill, 'fill'), stroke = colourOf(s.stroke, 'stroke');
    const strokeWidth = stroke ? s.strokeWidth * t.k : 0;
    const evenOdd = s.fillRule === 'evenodd';
    if (stroke && s.lineJoin !== 'round') fail(`stroke corners must be round (stroke-linejoin: round)`);
    if (s.tag === 'rect') {
        const n = k => Number(s.attr[k] || 0);
        const rx = s.attr.rx !== undefined ? n('rx') : n('ry'), ry = s.attr.ry !== undefined ? n('ry') : rx;
        if (Math.abs(rx - ry) > 1e-6) fail('rect corners must be circular (rx = ry)');
        const [x, y] = t.map(n('x'), n('y'));
        const w = n('width') * t.k, h = n('height') * t.k;
        return { kind: 'roundRect', x, y, w, h, r: Math.min(rx * t.k, w / 2, h / 2), fill, stroke, strokeWidth, evenOdd };
    }
    if (s.tag === 'circle') {
        const n = k => Number(s.attr[k] || 0);
        const [cx, cy] = t.map(n('cx'), n('cy'));
        return { kind: 'circle', cx, cy, r: n('r') * t.k, fill, stroke, strokeWidth, evenOdd };
    }
    if (s.tag === 'path') {
        const polys = snap(parsePolygons(s.attr.d).map(p => p.map(([x, y]) => t.map(x, y))));
        return { kind: 'polygons', polys, fill, stroke, strokeWidth, evenOdd };
    }
    fail(`<${s.tag}> elements`);
}

// ---------- 3. vector drawable writing (units → dp, numbers to 3 decimals = 1/1000 dp) ----------

function writer(canvas, fit = 1) {
    // fit < 1 shrinks the foreground around the canvas centre (see "How the artwork maps" above)
    const scale = VISIBLE_DP / canvas * fit, offset = (LAYER_DP - VISIBLE_DP * fit) / 2;
    const dp = v => offset + v * scale;
    // Round once, in thousandths, so equal artwork values stay exactly equal in the output.
    const f = v => { const n = Math.round(v * 1000) / 1000; return Object.is(n, -0) ? '0' : String(n); };
    const roundRect = ({ x, y, w, h, r }) => {
        const [x0, y0, x1, y1, R] = [dp(x), dp(y), dp(x + w), dp(y + h), r * scale];
        const a = (ex, ey) => `A${f(R)} ${f(R)} 0 0 1 ${f(ex)} ${f(ey)}`;
        return `M${f(x0 + R)} ${f(y0)}H${f(x1 - R)}${a(x1, y0 + R)}V${f(y1 - R)}${a(x1 - R, y1)}`
            + `H${f(x0 + R)}${a(x0, y1 - R)}V${f(y0 + R)}${a(x0 + R, y0)}Z`;
    };
    const polygons = polys => polys.map(p => {
        let out = `M${f(dp(p[0][0]))} ${f(dp(p[0][1]))}`;
        for (let i = 1; i < p.length; i++) {
            const [px, py] = p[i - 1], [x, y] = p[i];
            if (y === py) out += `H${f(dp(x))}`;          // horizontal / vertical edges: shorter and exact
            else if (x === px) out += `V${f(dp(y))}`;
            else out += `L${f(dp(x))} ${f(dp(y))}`;
        }
        return out + 'Z';
    }).join('');
    // a circle as two half-circle arcs (VectorDrawable path data has no circle command)
    const circle = ({ cx, cy, r }) => {
        const [x, y, R] = [dp(cx), dp(cy), r * scale];
        return `M${f(x - R)} ${f(y)}A${f(R)} ${f(R)} 0 1 0 ${f(x + R)} ${f(y)}A${f(R)} ${f(R)} 0 1 0 ${f(x - R)} ${f(y)}Z`;
    };
    const pathData = s => s.kind === 'roundRect' ? roundRect(s) : s.kind === 'circle' ? circle(s) : polygons(s.polys);
    const pathXml = (data, { fill, stroke, strokeWidth, evenOdd }) => '    <path\n'
        + (fill ? `        android:fillColor="${fill}"\n` : '')
        + (evenOdd ? '        android:fillType="evenOdd"\n' : '')
        + (stroke ? `        android:strokeColor="${stroke}"\n        android:strokeWidth="${f(strokeWidth * scale)}"\n`
            + '        android:strokeLineJoin="round"\n        android:strokeLineCap="round"\n' : '')
        + `        android:pathData="${data}" />\n`;
    const vector = paths => '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        + `    android:width="${LAYER_DP}dp"\n    android:height="${LAYER_DP}dp"\n`
        + `    android:viewportWidth="${LAYER_DP}"\n    android:viewportHeight="${LAYER_DP}">\n`
        + paths.join('') + '</vector>\n';
    return { scale, pathData, pathXml, vector };
}

// ---------- 4. checks on the geometry ----------

/** Farthest distance (artwork units) of any painted point from the canvas centre. */
function farthest(shapes, c) {
    let max = 0;
    for (const s of shapes) {
        const pad = s.stroke ? s.strokeWidth / 2 : 0;
        if (s.kind === 'circle') {
            max = Math.max(max, Math.hypot(s.cx - c, s.cy - c) + s.r + pad);
        } else if (s.kind === 'roundRect') {
            for (const [cx, cy] of [[s.x + s.r, s.y + s.r], [s.x + s.w - s.r, s.y + s.r], [s.x + s.r, s.y + s.h - s.r], [s.x + s.w - s.r, s.y + s.h - s.r]]) {
                max = Math.max(max, Math.hypot(cx - c, cy - c) + s.r + pad);
            }
        } else {
            for (const [x, y] of s.polys.flat()) max = Math.max(max, Math.hypot(x - c, y - c) + pad);
        }
    }
    return max;
}

/** Is the circle (px, py, radius) completely inside the rounded rectangle? */
function circleInRoundRect(px, py, radius, s) {
    const cx = Math.min(Math.max(px, s.x + s.r), s.x + s.w - s.r);
    const cy = Math.min(Math.max(py, s.y + s.r), s.y + s.h - s.r);
    return px - radius >= s.x && px + radius <= s.x + s.w && py - radius >= s.y && py + radius <= s.y + s.h
        && Math.hypot(px - cx, py - cy) + radius <= s.r + 1e-9;
}

// ---------- 5. the themed-icon (monochrome) layer ----------
//
// Android 13+ "Themed icons" draw this layer in one system colour on a light or dark tinted circle; only its
// shape (alpha) counts. It mirrors the light/dark areas of the colour icon:
//   cream speech bubble → drawn, as a ring (the dark screen is cut out of it);
//   bubble tail         → drawn;
//   coloured sprites    → drawn inside the cut-out.
// The tail's top corners reach under the screen (hidden in colour, because the screen is painted over them).
// In one colour they would show, so this layer slides them along their own edges into the middle of the cream
// frame. The tail edges below the bubble are on the same lines, so the visible tail does not change.

function monochromeShapes(fg) {
    // Two layouts: the 2026-10-02 artwork (bubble, tail, screen: rects) and the 2026-10-16 one (bubble circle,
    // tail, screen circle). Always in this order: bubble, tail, screen, then the sprites.
    const roundish = s => s?.kind === 'roundRect' || s?.kind === 'circle';
    const isTail = s => s?.kind === 'polygons' && s.stroke && s.polys.length === 1;
    let bubble, tail, screen, sprites;
    if (roundish(fg[0]) && isTail(fg[1]) && roundish(fg[2])) [bubble, tail, screen, ...sprites] = fg;
    const ok = bubble && screen && bubble.kind === screen.kind && sprites.length > 0
        && sprites.every(s => s.kind === 'polygons' && !s.stroke);
    if (!ok) fail('the foreground is expected as: bubble (rect or circle), tail (stroked path), screen (same kind as the bubble), then sprite paths');
    const circles = bubble.kind === 'circle';
    const inside = (outer, inner) => circles
        ? Math.hypot(inner.cx - outer.cx, inner.cy - outer.cy) + inner.r <= outer.r
        : inner.x >= outer.x && inner.y >= outer.y && inner.x + inner.w <= outer.x + outer.w && inner.y + inner.h <= outer.y + outer.h;
    const inScreen = (x, y) => circles ? Math.hypot(x - screen.cx, y - screen.cy) <= screen.r
        : x >= screen.x && x <= screen.x + screen.w && y >= screen.y && y <= screen.y + screen.h;
    if (!inside(bubble, screen)) stop('the screen must lie inside the bubble');
    for (const s of sprites) for (const [x, y] of s.polys.flat()) {
        if (!inScreen(x, y)) stop('sprites must lie inside the screen');
    }
    if (circles) {
        // Round layout: the tail's corners must already lie outside the screen (in the white ring or beyond),
        // because one colour would show a corner hidden under the screen. Moving them is only done for rects.
        // Only the corners are checked: an edge cutting into the screen circle would not be noticed (the
        // 2026-10-16 artwork's tail clears it by about 0.4 units including the stroke).
        if (tail.polys[0].some(([x, y]) => inScreen(x, y))) stop('a tail corner lies under the round screen; move it into the ring in the artwork');
        return { bubble, screen, tail, sprites, yMid: null };
    }
    const screenBottom = screen.y + screen.h, bubbleBottom = bubble.y + bubble.h;
    const yMid = (screenBottom + bubbleBottom) / 2;
    const under = ([x, y]) => x >= screen.x && x <= screen.x + screen.w && y >= screen.y && y <= screenBottom;
    const pts = tail.polys[0];
    const moved = pts.map((p, i) => {
        if (!under(p)) return p;
        // slide towards a neighbour that is outside the screen, stopping at yMid
        const nb = [pts[(i + pts.length - 1) % pts.length], pts[(i + 1) % pts.length]].find(q => !under(q));
        if (!nb) fail('a tail corner under the screen has no neighbour outside it');
        const t = (yMid - p[1]) / (nb[1] - p[1]);
        return [p[0] + t * (nb[0] - p[0]), yMid];
    });
    const r = tail.strokeWidth / 2;
    const ring = { x: bubble.x, y: bubble.y, w: bubble.w, h: bubble.h, r: bubble.r };
    for (let i = 0; i < pts.length; i++) {
        if (moved[i] === pts[i]) continue;
        const [x, y] = moved[i];
        // the moved corner (with its round stroke) must sit in the cream frame: inside the bubble, below the screen
        if (!(circleInRoundRect(x, y, r, ring) && y - r > screenBottom)) stop('the moved tail corner does not fit in the cream frame (is the frame thinner than the tail outline?)');
    }
    return { bubble, screen, tail: { ...tail, polys: [moved] }, sprites, yMid };
}

// ---------- 6. main ----------

async function main() {
    const svgText = readFileSync(SOURCE, 'utf8');
    const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
    try {
        const page = await browser.newPage();
        const art = await readArtwork(page, svgText);
        if (art.unsupported.length) fail(`<${[...new Set(art.unsupported)].join('>, <')}> elements`);
        const [vx, vy, W, H] = art.viewBox;
        if (vx !== 0 || vy !== 0 || W !== H) fail(`the canvas must be square and start at 0 0 (viewBox ${art.viewBox.join(' ')})`);

        const [bgRaw, ...fgRaw] = art.shapes;
        const bg = bgRaw && toShape(bgRaw);
        if (!bg || bg.kind !== 'roundRect' || Math.abs(bg.x) > 1e-6 || Math.abs(bg.y) > 1e-6
            || Math.abs(bg.w - W) > 1e-6 || Math.abs(bg.h - H) > 1e-6 || bg.stroke) {
            fail('the first shape must be the background: a rect covering the whole canvas, without a stroke');
        }
        const fg = fgRaw.map(toShape);

        // nothing may be cut by a circular launcher mask: shrink the foreground just enough if it reaches past 36 dp
        const far = farthest(fg, W / 2) * VISIBLE_DP / W;
        const fit = far > VISIBLE_RADIUS_DP ? VISIBLE_RADIUS_DP / far : 1;
        const out = writer(W, fit);
        const reach = far * fit;

        // background colour
        writeFileSync(join(RES, 'values', 'ic_launcher_background.xml'), '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER
            + `<resources>\n    <color name="ic_launcher_background">${bg.fill}</color>\n</resources>\n`);

        // foreground: every shape in order, own colours
        const fgXml = out.vector(fg.map(s => out.pathXml(out.pathData(s), s)));
        writeFileSync(join(RES, 'drawable', 'ic_launcher_foreground.xml'), fgXml);

        // monochrome: ring (bubble with the screen cut out, even-odd fill), tail, sprites; one colour
        const mono = monochromeShapes(fg), white = { fill: '#FFFFFF' };
        const monoXml = out.vector([
            out.pathXml(out.pathData(mono.bubble) + out.pathData(mono.screen), { ...white, evenOdd: true }),
            out.pathXml(out.pathData(mono.tail), { ...white, stroke: '#FFFFFF', strokeWidth: mono.tail.strokeWidth }),
            // one path per sprite colour, as in the foreground (lint's VectorPath warns about very long paths)
            ...mono.sprites.map(s => out.pathXml(out.pathData(s), { ...white, evenOdd: s.evenOdd })),
        ]);
        writeFileSync(join(RES, 'drawable', 'ic_launcher_monochrome.xml'), monoXml);

        // PNGs: the artwork itself (with its rounded background), drawn by Chromium straight at each size
        const png = async (px, file) => {
            // draw the SVG at exactly px x px: replace its own width/height (the viewBox keeps the drawing the same)
            const open = /<svg\b[^>]*>/.exec(svgText)[0];
            if (!/\swidth="[^"]*"/.test(open) || !/\sheight="[^"]*"/.test(open)) fail('the <svg> tag needs width and height');
            const sized = svgText.replace(/<\?xml[^>]*>|<!DOCTYPE[^>]*>/g, '')
                .replace(open, open.replace(/\swidth="[^"]*"/, ` width="${px}"`).replace(/\sheight="[^"]*"/, ` height="${px}"`));
            await page.setViewportSize({ width: px, height: px });
            await page.setContent(`<!doctype html><body style="margin:0;background:transparent">${sized.replace('<svg ', '<svg style="display:block" ')}</body>`);
            mkdirSync(dirname(file), { recursive: true });
            await page.screenshot({ path: file, omitBackground: true, clip: { x: 0, y: 0, width: px, height: px } });
        };
        for (const [density, px] of Object.entries(LEGACY)) await png(px, join(RES, `mipmap-${density}`, 'ic_launcher.png'));
        await png(STORE_PX, STORE_ICON);

        console.log(`background ${bg.fill}; ${fg.length} foreground shapes; farthest point ${far.toFixed(2)} dp`
            + (fit < 1 ? `, foreground scaled by ${fit.toFixed(4)} to ${reach.toFixed(2)} dp (visible circle ${VISIBLE_RADIUS_DP} dp)` : '')
            + (reach > SAFE_RADIUS_DP ? `; NOTE: reaches past the ${SAFE_RADIUS_DP} dp safe zone (fine for a tail tip, not for key content)` : '')
            + (mono.yMid !== null ? `; monochrome tail corners moved to y=${mono.yMid.toFixed(2)} units` : '; monochrome tail unchanged')
            + `; ${Object.keys(LEGACY).length} legacy PNGs + ${STORE_PX} px store icon written.`);
    } finally {
        await browser.close();
    }
}

main().catch(e => { console.error(e.message); process.exit(1); });
